// Use a preinstalled Playwright through NODE_PATH; no server or persistent browser.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {pathToFileURL} = require('node:url');

(async()=>{
  const root=path.resolve(__dirname,'..');
  const url=process.argv[2] || pathToFileURL(path.join(root,'_site/index.html')).href;
  const server=await chromium.launchServer({channel:'msedge',headless:true,timeout:20000});
  const processInfo={pid:server.process().pid,started:new Date().toISOString(),purpose:'GitHub Pages browser verification',owner:'this task'};
  console.log(JSON.stringify(processInfo));
  let browser;
  try {
    browser=await chromium.connect(server.wsEndpoint());
    const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    page.setDefaultTimeout(10000);
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url+'#R01');
    await page.locator('[data-node="R01"] circle').waitFor();
    await page.waitForFunction(()=>{const graph=document.getElementById('graph');return graph.dataset.running==='true'&&performance.now()-Number(graph.dataset.settlingStarted)>=2500;},{},{timeout:5000});
    await page.waitForFunction(()=>document.getElementById('graph').dataset.running==='false',{},{timeout:10000});
    assert.ok(await page.evaluate(()=>performance.now()-Number(document.getElementById('graph').dataset.settlingStarted)>=3000));
    assert.equal(await page.locator('#nodes .graph-node').count(),34);
    assert.match(await page.locator('#detail-meta').innerText(),/R01/);
    assert.match(await page.locator('#detail-meta').innerText(),/未確認|条件付き/);
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    assert.equal(await page.locator('#nodes .selected').count(),0);
    assert.equal(await page.locator('#global-graph, #local-graph').count(),0);
    assert.ok(await page.locator('#nodes text').evaluateAll(labels=>labels.every(label=>getComputedStyle(label).opacity==='1')));
    await page.locator('[data-node="R01"] circle').hover();
    assert.ok(await page.locator('#nodes .dimmed').count()>0);
    await page.locator('.brand').hover();
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    await page.locator('[data-node="R01"]').focus();
    assert.ok(await page.locator('#nodes .dimmed').count()>0);
    await page.locator('#search').focus();
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    await page.locator('[data-node="R02"] circle').click();
    await page.waitForFunction(()=>location.hash==='#R02');
    assert.match(await page.locator('#detail-meta').innerText(),/R02/);
    assert.ok(await page.locator('#nodes .dimmed').count()>0);
    await page.locator('#graph').click({position:{x:8,y:140}});
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    await page.locator('[data-node="R02"] circle').click();
    assert.ok(await page.locator('#nodes .dimmed').count()>0);
    await page.keyboard.press('Escape');
    await page.locator('.brand').hover();
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    await page.locator('#reset-graph').click();
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    await page.goBack();
    assert.match(await page.locator('#detail-meta').innerText(),/R01/);
    assert.ok(await page.locator('#detail-content a[href*="page=23"]').count());
    await page.locator('#detail-scope').click();
    assert.equal(await page.locator('#nodes .graph-node').count(),43);
    await page.locator('[data-note="W01"]').click();
    await page.waitForFunction(()=>document.getElementById('detail-meta').textContent.includes('W01'));
    assert.match(await page.locator('#detail-meta').innerText(),/まだ証拠|未獲得|供述候補/);
    assert.match(await page.locator('.relation-section').innerText(),/将来|現在は/);
    await page.locator('#main-scope').click();
    assert.equal(await page.locator('#nodes .graph-node').count(),34);
    await page.locator('#search').fill('zzzz-not-found');
    assert.equal(await page.locator('#nodes .graph-node').count(),0);
    assert.equal(await page.locator('#empty').isVisible(),true);
    await page.locator('#search').fill('眼鏡');
    assert.ok(await page.locator('#note-list a').count()>0);
    await page.locator('#search').fill('');
    await page.locator('#side').selectOption('弁護');
    assert.equal(await page.locator('#nodes .graph-node').count(),9);
    await page.locator('#side').selectOption('');
    await page.locator('#zoom-in').click();
    assert.match(await page.locator('#camera').getAttribute('transform'),/scale\(1.25\)/);
    await page.locator('#reset-graph').click();
    const images=path.join(root,'作成用/構造化確認');fs.mkdirSync(images,{recursive:true});
    await page.waitForFunction(()=>document.getElementById('graph').dataset.running==='false',{},{timeout:10000});
    await page.screenshot({path:path.join(images,'Pages_PC.png'),fullPage:true});
    await page.locator('.header-links a').first().click();
    assert.match(await page.locator('#detail-content').innerText(),/Obsidianを初めて/);
    await page.locator('#document-picker').selectOption('docs/03_証拠と利用範囲.md');
    assert.match(await page.locator('#detail-content').innerText(),/採否留保/);
    await page.goto(url+'?scope=detail#W01');
    assert.equal(await page.locator('#nodes .graph-node').count(),43);
    await page.setViewportSize({width:390,height:844});
    await page.goto(url+'#R01');
    await page.reload();
    assert.equal(await page.locator('#graph .dimmed').count(),0);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.waitForFunction(()=>document.getElementById('graph').dataset.running==='false',{},{timeout:10000});
    await page.screenshot({path:path.join(images,'Pages_スマホ.png'),fullPage:true});
    await page.locator('#detail-scope').click();
    await page.locator('[data-note="W01"]').click();
    await page.waitForFunction(()=>document.getElementById('detail-meta').textContent.includes('W01'));
    assert.match(await page.locator('#detail-meta').innerText(),/W01/);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const inherited=await page.evaluate(()=>window.TRIAL_GRAPH.graph_settings.options);
    assert.equal(await page.locator('#center-strength').inputValue(),String(inherited.centerStrength));
    assert.equal(await page.locator('#link-distance').inputValue(),String(inherited.linkDistance));
    assert.equal(await page.locator('#graph').getAttribute('data-engine'),'d3-force');
    await page.locator('#graph-settings summary').click();
    await page.locator('#center-strength').fill('0.23');
    await page.locator('#center-strength').dispatchEvent('input');
    await page.reload();
    assert.equal(await page.locator('#center-strength').inputValue(),'0.23');
    await page.locator('#graph-settings summary').click();
    await page.locator('#restore-settings').click();
    assert.equal(await page.locator('#center-strength').inputValue(),String(inherited.centerStrength));
    await page.locator('#graph-settings summary').click();
    await page.goto(url+'?scope=detail&graph=local#W01');
    assert.equal(await page.locator('#nodes .graph-node').count(),43);
    assert.equal(await page.locator('#global-graph, #local-graph').count(),0);
    assert.equal(new URL(page.url()).searchParams.has('graph'),false);
    const dynamics=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
    dynamics.on('pageerror',e=>errors.push(e.message));
    await dynamics.goto(url+'#T01');
    await dynamics.waitForFunction(()=>{const graph=document.getElementById('graph');return graph.dataset.running==='true'&&performance.now()-Number(graph.dataset.settlingStarted)>=2500;},{},{timeout:5000});
    await dynamics.waitForFunction(()=>document.getElementById('graph').dataset.running==='false',{},{timeout:10000});
    assert.ok(await dynamics.evaluate(()=>performance.now()-Number(document.getElementById('graph').dataset.settlingStarted)>=3000));
    const neighbor=dynamics.locator('[data-node="R02"]');
    const before=await neighbor.getAttribute('transform');
    const circle=dynamics.locator('[data-node="T01"] circle');
    const box=await circle.boundingBox();
    await dynamics.mouse.move(box.x+box.width/2,box.y+box.height/2);
    await dynamics.mouse.down();
    await dynamics.mouse.move(box.x+box.width/2+100,box.y+box.height/2+50,{steps:12});
    await dynamics.mouse.up();
    await dynamics.waitForFunction(previous=>document.querySelector('[data-node="R02"]').getAttribute('transform')!==previous,before);
    assert.equal(new URL(dynamics.url()).hash,'#T01');
    await dynamics.waitForFunction(()=>{const graph=document.getElementById('graph');return graph.dataset.running==='true'&&performance.now()-Number(graph.dataset.settlingStarted)>=2500;},{},{timeout:5000});
    await dynamics.locator('#pause-layout').click();
    assert.equal(await dynamics.locator('#graph').getAttribute('data-running'),'false');
    await dynamics.locator('#graph-settings summary').click();
    await dynamics.locator('#pause-layout').click();
    await dynamics.locator('#center-strength').fill('0.31');
    await dynamics.locator('#center-strength').dispatchEvent('input');
    await dynamics.waitForFunction(()=>{const graph=document.getElementById('graph');return graph.dataset.running==='true'&&performance.now()-Number(graph.dataset.settlingStarted)>=2500;},{},{timeout:5000});
    await dynamics.locator('#pause-layout').click();
    assert.equal(await dynamics.locator('#graph').getAttribute('data-running'),'false');
    await dynamics.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: minimum settling interval for normal/reduced motion and force changes/drag, manual stop, brightness, desktop/mobile, inherited settings and existing navigation');
  } finally {
    if(browser)await browser.close();
    await server.close();
    console.log('Task-owned browser closed: '+processInfo.pid);
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
