def build():
    manifest=[]
    for b in BOOKS:
        flow=[]; txt=[b['title'],'']
        for i,pg in enumerate(b['pages']):
            if i: flow.append(PageBreak())
            flow.append(P(pg['title'],'title')); txt.extend(['',pg['title'],''])
            for block in pg['blocks']:
                typ=block['type']
                if typ in ('p','h','small','script'):
                    flow.append(P(block['text'],typ));txt.append(block['text']+'\n')
                elif typ=='table':
                    flow.append(table(block['rows'],block['widths']));flow.append(Spacer(1,8))
                    txt.extend([' | '.join(map(str,r)) for r in block['rows']]);txt.append('')
                elif typ=='diagram':
                    flow.append(diagram(block['kind']));txt.append('図はPDFを参照。関連する説明と出典は本文に記載。')
                elif typ=='lines':
                    for _ in range(block['n']): flow.append(P('________________________________________________________________','small'));flow.append(Spacer(1,9))
        pdf=OUT/(b['name']+'.pdf')
        doc=SimpleDocTemplate(str(pdf),pagesize=A4,rightMargin=48,leftMargin=48,topMargin=48,bottomMargin=48,title=b['title'],author='検察官準備資料',pageCompression=1)
        doc.build(flow,onFirstPage=lambda c,d,title=b['title']:footer(c,d,title),onLaterPages=lambda c,d,title=b['title']:footer(c,d,title))
        (EDIT/(b['name']+'.txt')).write_text('\n'.join(txt),encoding='utf-8-sig')
        manifest.append({'file':str(pdf.relative_to(ROOT)),'planned_pages':len(b['pages']),'sha256':hashlib.sha256(pdf.read_bytes()).hexdigest()})
    (EDIT/'資料データ.json').write_text(json.dumps(BOOKS,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'tmp'/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    write_index()
    print(json.dumps(manifest,ensure_ascii=False,indent=2))

